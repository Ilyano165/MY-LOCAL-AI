HF_FILE = "https://huggingface.co/{repo}/resolve/{revision}/{file}"
MANAGED_MARKER = "# managed by NOVA – generated by the one-click setup"
Progress = Callable[[str, int, int], None]


class RuntimeError_(Exception):  # eigener Name, kollidiert nicht mit builtins
    def __init__(self, code: str, message: str, status: int = 400) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.status = status


# ---------------------------------------------------------------------- Hardware


@dataclass
class GpuInfo:
    name: str
    vram_gb: float
    compute_capability: str | None
    driver: str | None


def detect_gpu(run: Callable[..., Any] = subprocess.run) -> GpuInfo | None:
    exe = shutil.which("nvidia-smi")
    if exe is None:
        return None
    try:
        out = run(
            [
                exe,
                "--query-gpu=name,memory.total,driver_version,compute_cap",
                "--format=csv,noheader,nounits",
            ],
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if out.returncode != 0 or not out.stdout.strip():
        return None
    parts = [p.strip() for p in out.stdout.splitlines()[0].split(",")]
    try:
        vram = round(float(parts[1]) / 1024, 1)
    except (IndexError, ValueError):
        return None
    cc = parts[3] if len(parts) > 3 and re.match(r"^\d+\.\d+$", parts[3]) else None
    return GpuInfo(parts[0], vram, cc, parts[2] if len(parts) > 2 else None)


def total_ram_gb() -> float | None:
    from api.model_manager import total_ram_gb as ram

    return ram()


# ---------------------------------------------------------------------- Auflösung


@dataclass
class Artifact:
    name: str
    url: str
    sha256: str
    size: int


@dataclass
class ModelSpec:
    id: str
    label: str
    repo: str
    registry_name: str
    file: str
    revision: str
    sha256: str
    size: int
    license: str
    license_url: str
    settings: dict[str, Any] = field(default_factory=dict)

    @property
    def url(self) -> str:
        return HF_FILE.format(repo=self.repo, revision=self.revision, file=self.file)


def recommended_models(config_path: Path) -> list[dict[str, Any]]:
    data = json.loads(config_path.read_text(encoding="utf-8"))
    return list(data.get("models", []))


def choose_model(
    models: list[dict[str, Any]], gpu: GpuInfo | None, ram: float | None
) -> dict[str, Any]:
    """Größtes empfohlenes Modell, das zu VRAM (GPU) bzw. RAM (CPU) passt."""
    for spec in models:  # Reihenfolge in der Datei: groß → klein
        vram_ok = gpu is not None and gpu.vram_gb >= spec.get("min_vram_gb", 0)
        cpu_ok = spec.get("min_vram_gb", 0) == 0
        ram_ok = ram is None or ram >= spec.get("min_ram_gb", 0)
        if (vram_ok or cpu_ok) and ram_ok:
            return spec
    return models[-1]


def llama_variant(gpu: GpuInfo | None, platform: str = sys.platform) -> str:
    if platform != "win32":
        return "unsupported"
    return "cuda12" if gpu is not None else "cpu"


_ASSET_PATTERNS = {
    "cuda12": (
        re.compile(r"^llama-b\d+-bin-win-cuda-?(?:cu)?12[\d.]*-x64\.zip$"),
        re.compile(r"^cudart-llama-bin-win-cuda-?(?:cu)?12[\d.]*-x64\.zip$"),
    ),
    "cpu": (re.compile(r"^llama-b\d+-bin-win-(?:cpu|avx2)-x64\.zip$"), None),
}


def _digest(asset: dict[str, Any]) -> str | None:
    digest = str(asset.get("digest") or "")
    if digest.startswith("sha256:") and re.match(r"^[0-9a-f]{64}$", digest[7:]):
        return digest[7:]
    return None


def pick_llama_assets(release: dict[str, Any], variant: str) -> tuple[str, list[Artifact]]:
    if variant not in _ASSET_PATTERNS:
        raise RuntimeError_(
            "unsupported_platform",
            "The one-click runtime is available for Windows only – install llama.cpp manually.",
        )
    tag = str(release.get("tag_name") or "")
    assets = release.get("assets") or []
    picked: list[Artifact] = []
    for pattern in _ASSET_PATTERNS[variant]:
        if pattern is None:
            continue
        matches = sorted(
            (a for a in assets if pattern.match(str(a.get("name", "")))),
            key=lambda a: str(a["name"]),
            reverse=True,
        )
        if not matches:
            raise RuntimeError_(
                "runtime_not_found",
                f"No llama.cpp {variant} build found in release {tag or '?'} – try again later "
                "or install llama.cpp manually.",
                502,
            )
        asset = matches[0]
        digest = _digest(asset)
        if digest is None:
            raise RuntimeError_(
                "no_checksum",
                f"Release asset {asset['name']} has no published SHA-256 – not installed.",
                502,
            )
        url = str(asset.get("browser_download_url") or "")
        if not url.startswith("https://"):
            raise RuntimeError_("runtime_not_found", "Release asset has no HTTPS download URL", 502)
        picked.append(Artifact(str(asset["name"]), url, digest, int(asset.get("size") or 0)))
    return tag, picked


def pick_model_file(info: dict[str, Any], spec: dict[str, Any]) -> ModelSpec:
    revision = str(info.get("sha") or "")
    if not re.match(r"^[0-9a-f]{40}$", revision):
        raise RuntimeError_(
            "model_not_found", f"{spec['repo']}: no commit revision in API answer", 502
        )
    files = {
        str(s.get("rfilename")): s
        for s in info.get("siblings") or []
        if str(s.get("rfilename", "")).endswith(".gguf")
        and "mmproj" not in str(s.get("rfilename", ""))
    }
    chosen = None
    for pref in spec.get("file_preference", []):
        if pref in files:
            chosen = pref
            break
        suffix = [f for f in sorted(files) if f.endswith(pref) and "/" not in f]
        if suffix:
            chosen = suffix[0]
            break
    if chosen is None:
        raise RuntimeError_("model_not_found", f"{spec['repo']}: no suitable GGUF file found", 502)
    lfs = files[chosen].get("lfs") or {}
    sha = str(lfs.get("sha256") or lfs.get("oid") or "")
    if not re.match(r"^[0-9a-f]{64}$", sha):
        raise RuntimeError_(
            "no_checksum", f"{chosen} has no published SHA-256 – not downloaded", 502
        )
    card = info.get("cardData") or {}
    license_id = str(card.get("license") or spec.get("base_license") or "unknown")
    return ModelSpec(
        id=str(spec["id"]),
        label=str(spec["label"]),
        repo=str(spec["repo"]),
        registry_name=str(spec["registry_name"]),
        file=chosen,
        revision=revision,
        sha256=sha,
        size=int(lfs.get("size") or files[chosen].get("size") or 0),
        license=license_id,
        license_url=f"https://huggingface.co/{spec['repo']}",
        settings={
            k: v for k, v in spec.items() if k not in ("id", "label", "repo", "file_preference")
        },
    )


# ---------------------------------------------------------------------- Download


async def fetch_verified(
    client: httpx.AsyncClient,
    artifact: Artifact,
    target: Path,
    *,
    progress: Progress | None = None,
    label: str = "",
) -> Path:
    """HTTPS-Download mit Fortsetzen (``.part``), Größen- und SHA-256-Prüfung, atomarer Ablage."""
    if await asyncio.to_thread(_already_valid, target, artifact.sha256):
        return target
    target.parent.mkdir(parents=True, exist_ok=True)
    part = target.with_name(target.name + ".part")
    offset = part.stat().st_size if part.is_file() else 0
    if artifact.size and offset > artifact.size:
        part.unlink()
        offset = 0
    headers = {"Range": f"bytes={offset}-"} if offset else {}
    try:
        async with client.stream("GET", artifact.url, headers=headers) as r:
            if not str(r.url).startswith("https://"):
                raise RuntimeError_(
                    "insecure_redirect", "Download redirected to non-HTTPS – aborted"
                )
            if offset and r.status_code == 200:
                offset = 0
                part.unlink(missing_ok=True)
            elif r.status_code not in (200, 206):
                raise RuntimeError_(
                    "download_failed", f"{artifact.name}: HTTP {r.status_code}", 502
                )
            done = offset
            with part.open("ab") as fh:
                async for chunk in r.aiter_bytes():
                    fh.write(chunk)
                    done += len(chunk)
                    if artifact.size and done > artifact.size:
                        raise RuntimeError_("download_failed", "more data than announced", 502)
                    if progress:
                        progress(label or artifact.name, done, artifact.size)
    except httpx.HTTPError as exc:
        raise RuntimeError_(
            "download_interrupted",
            f"{artifact.name}: download interrupted ({type(exc).__name__}) – start again to resume",
            502,
        ) from exc
    if artifact.size and part.stat().st_size != artifact.size:
        raise RuntimeError_(
            "download_interrupted", f"{artifact.name}: incomplete – start again", 502
        )
    if _sha256_file(part) != artifact.sha256:
        part.unlink()
        raise RuntimeError_(
            "checksum_mismatch", f"{artifact.name}: SHA-256 mismatch – discarded", 502
        )
    part.replace(target)
    return target


def _already_valid(path: Path, sha256: str) -> bool:
    return path.is_file() and _sha256_file(path) == sha256


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        while chunk := fh.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


def safe_extract(
    archive: Path, target: Path, include: Callable[[PurePosixPath], bool] | None = None
) -> None:
    """Entpackt ohne Pfad-Ausbruch (keine absoluten Pfade, kein ``..``).

    ``include`` wählt Einträge aus (z. B. nur den Konverter aus dem llama.cpp-Quellbaum –
    vermeidet zu lange Windows-Pfade und unnötige Dateien)."""
    target.mkdir(parents=True, exist_ok=True)
    root = target.resolve()
    with zipfile.ZipFile(archive) as zf:
        members = []
        for member in zf.infolist():
            name = PurePosixPath(member.filename)
            if name.is_absolute() or ".." in name.parts or ":" in member.filename:
                raise RuntimeError_("unsafe_archive", f"unsafe path in archive: {member.filename}")
            dest = (root / Path(*name.parts)).resolve()
            if not str(dest).startswith(str(root)):
                raise RuntimeError_("unsafe_archive", f"unsafe path in archive: {member.filename}")
            if include is None or include(name):
                members.append(member)
        zf.extractall(root, members=members)
        if os.name != "nt":  # Ausführungsrechte aus dem Archiv übernehmen (POSIX)
            for member in members:
                mode = (member.external_attr >> 16) & 0o777
                if mode:
                    (root / Path(*PurePosixPath(member.filename).parts)).chmod(mode)


def find_server(directory: Path) -> Path | None:
    for name in ("llama-server.exe", "llama-server"):
        found = sorted(directory.rglob(name))
        if found:
            return found[0]
    return None


