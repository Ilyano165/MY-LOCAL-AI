"""Verwaltete lokale Runtime: llama.cpp + Modell mit einem Klick einrichten und betreiben.

Ablauf der Einrichtung (``RuntimeManager.setup``):
1. Hardware erkennen (``nvidia-smi``; ohne NVIDIA-GPU → CPU-Build).
2. llama.cpp-Release über die **GitHub-API** auflösen (Asset + SHA-256-Digest der Release-Seite);
   unter Windows mit NVIDIA-GPU der CUDA-12-Build (unterstützt auch GTX-10-Karten) samt
   CUDA-Laufzeit-DLLs, sonst der CPU-Build.
3. Modell über die **Hugging-Face-API** auflösen (fester Commit, Datei, SHA-256, Größe, Lizenz).
4. Alles herunterladen (nur HTTPS, Fortsetzen, SHA-256-Prüfung), Archive sicher entpacken.
5. ``models.toml`` schreiben (nur, wenn keine eigene Konfiguration existiert) und
   ``llama-server`` als Kindprozess des Core starten; der Core lädt die Modelle neu.

Nichts wird ohne Lizenzbestätigung geladen; ohne veröffentlichte Prüfsumme wird nichts
installiert. Adressen/Prüfsummen stehen nicht im Code, sondern kommen aus den offiziellen APIs.
"""

