# ---------------------------------------------------------------------- Prozess


class RuntimeProcess:
    def __init__(self, log_path: Path) -> None:
        self.log_path = log_path
        self.process: subprocess.Popen[bytes] | None = None
        self.port: int | None = None
        self.args: list[str] = []

    @property
    def running(self) -> bool:
        return self.process is not None and self.process.poll() is None

    def start(self, server: Path, model: dict[str, Any], port: int, gpu: bool) -> None:
        self.stop()
        s = model["settings"]
        self.args = [
            str(server),
            "-m",
            str(model["path"]),
            "--alias",
            served_name(model),
            "--host",
            "127.0.0.1",
            "--port",
            str(port),
            "--ctx-size",
            str(int(s.get("context_length", 8192))),
            "--jinja",
        ]
        if gpu:
            self.args += ["-ngl", "99"]
        for adapter in model.get("lora", []):
            self.args += ["--lora", str(adapter)]
        self.log_path.parent.mkdir(parents=True, exist_ok=True)
        log_file = self.log_path.open("ab")
        kwargs: dict[str, Any] = {
            "stdout": log_file,
            "stderr": subprocess.STDOUT,
            "stdin": subprocess.DEVNULL,
            "cwd": str(server.parent),
        }
        if sys.platform == "win32":
            kwargs["creationflags"] = subprocess.CREATE_NO_WINDOW
        self.process = subprocess.Popen(self.args, **kwargs)
        self.port = port

    def wait_ready(self, timeout_s: float = 300.0) -> None:
        deadline = time.time() + timeout_s
        while time.time() < deadline:
            if not self.running:
                raise RuntimeError_(
                    "runtime_crashed", f"llama-server stopped – see {self.log_path}", 500
                )
            with contextlib.suppress(httpx.HTTPError):
                r = httpx.get(f"http://127.0.0.1:{self.port}/health", timeout=2)
                if r.status_code == 200:
                    return
            time.sleep(1)
        raise RuntimeError_(
            "runtime_timeout", f"llama-server did not become ready – see {self.log_path}", 504
        )

    def stop(self) -> None:
        if self.process is not None and self.process.poll() is None:
            self.process.terminate()
            try:
                self.process.wait(timeout=15)
            except subprocess.TimeoutExpired:
                self.process.kill()
        self.process = None


# ---------------------------------------------------------------------- Manager


class RuntimeManager:
    def __init__(
        self,
        layout: DataLayout,
        recommended_path: Path,
        *,
        client_factory: Callable[[], httpx.AsyncClient] | None = None,
        gpu_detector: Callable[[], GpuInfo | None] = detect_gpu,
        platform: str = sys.platform,
    ) -> None:
        self.layout = layout
        self.recommended_path = recommended_path
        self.client_factory = client_factory or (
            lambda: httpx.AsyncClient(
                timeout=httpx.Timeout(60, connect=20),
                follow_redirects=True,
                headers={"User-Agent": "NOVA-Setup"},
            )
        )
        self.gpu_detector = gpu_detector
        self.platform = platform
        self.process = RuntimeProcess(layout.logs / "llama-server.log")
        self.progress: dict[str, Any] = {"status": "idle"}
        self._task: asyncio.Task[None] | None = None
        self._gpu: GpuInfo | None = None
        self._gpu_checked = False

    @property
    def state_path(self) -> Path:
        return self.layout.root / "runtime.json"

    def state(self) -> dict[str, Any]:
        try:
            data: dict[str, Any] = json.loads(self.state_path.read_text(encoding="utf-8"))
            return data
        except (OSError, ValueError):
            return {}

    def _save(self, state: dict[str, Any]) -> None:
        tmp = self.state_path.with_suffix(".tmp")
        tmp.write_text(json.dumps(state, indent=2), encoding="utf-8")
        os.replace(tmp, self.state_path)

    def gpu(self) -> GpuInfo | None:
        if not self._gpu_checked:
            self._gpu = self.gpu_detector()
            self._gpu_checked = True
        return self._gpu

    def status(self) -> dict[str, Any]:
        gpu = self.gpu()
        ram = total_ram_gb()
        try:
            models = recommended_models(self.recommended_path)
            rec = choose_model(models, gpu, ram) if models else None
        except (OSError, ValueError):
            models, rec = [], None
        state = self.state()
        return {
            "platform_supported": llama_variant(gpu, self.platform) != "unsupported",
            "gpu": gpu.__dict__ if gpu else None,
            "ram_gb": round(ram, 1) if ram else None,
            "variant": llama_variant(gpu, self.platform),
            "recommended": rec,
            "choices": models,
            "installed": state.get("model"),
            "runtime_tag": state.get("runtime_tag"),
            "running": self.process.running,
            "port": self.process.port,
            "setup": self.progress,
            "custom_config": self._custom_config(),
        }

    def _custom_config(self) -> bool:
        path = self.layout.models_config
        return path.is_file() and MANAGED_MARKER not in path.read_text(encoding="utf-8")[:200]

    def _report(self, label: str, done: int, total: int) -> None:
        self.progress.update({"status": "downloading", "item": label, "done": done, "total": total})

    async def setup(
        self, choice: str | None, accept_license: bool, on_ready: Callable[[], None]
    ) -> dict[str, Any]:
        if self._task is not None and not self._task.done():
            raise RuntimeError_("already_running", "Setup is already running", 409)
        gpu = self.gpu()
        variant = llama_variant(gpu, self.platform)
        if variant == "unsupported":
            raise RuntimeError_(
                "unsupported_platform",
                "The one-click setup is available on Windows. Install llama.cpp manually.",
            )
        if self._custom_config():
            raise RuntimeError_(
                "custom_config",
                f"{self.layout.models_config} was written by you – it is not overwritten.",
                409,
            )
        models = recommended_models(self.recommended_path)
        spec = next((m for m in models if m["id"] == choice), None) if choice else None
        spec = spec or choose_model(models, gpu, total_ram_gb())
        async with self.client_factory() as client:
            try:
                info = (await client.get(HF_API.format(repo=spec["repo"]))).json()
            except (httpx.HTTPError, ValueError) as exc:
                raise RuntimeError_(
                    "model_not_found", f"Hugging Face not reachable: {exc}", 502
                ) from exc
        model = pick_model_file(info, spec)
        if not accept_license:
            raise RuntimeError_(
                "license_not_accepted",
                f"Accept the model license first: {model.license} ({model.license_url})",
            )
        free = shutil.disk_usage(self.layout.root).free
        need = int(model.size * 1.1) + 600_000_000
        if free < need:
            raise RuntimeError_(
                "not_enough_disk",
                f"Not enough disk space: {need / 1e9:.1f} GB needed, {free / 1e9:.1f} GB free",
            )
        self.progress = {
            "status": "starting",
            "model": model.label,
            "size": model.size,
            "license": model.license,
            "error": None,
        }
        self._task = asyncio.create_task(self._install(model, variant, gpu, on_ready))
        return {"status": "started", "model": model.__dict__ | {"url": model.url}}

    async def _install(
        self, model: ModelSpec, variant: str, gpu: GpuInfo | None, on_ready: Callable[[], None]
    ) -> None:
        try:
            async with self.client_factory() as client:
                release = (await client.get(GITHUB_RELEASES)).json()
                tag, artifacts = pick_llama_assets(release, variant)
                runtime_dir = self.layout.root / "runtime" / f"llama.cpp-{tag}-{variant}"
                downloads = self.layout.root / "runtime" / ".downloads"
                for artifact in artifacts:
                    path = await fetch_verified(
                        client,
                        artifact,
                        downloads / artifact.name,
                        progress=self._report,
                        label=artifact.name,
                    )
                    self.progress["status"] = "extracting"
                    await asyncio.to_thread(safe_extract, path, runtime_dir)
                server = find_server(runtime_dir)
                if server is None:
                    raise RuntimeError_(
                        "runtime_not_found", "llama-server not found in the release", 502
                    )
                model_path = self.layout.models / model.file
                await fetch_verified(
                    client,
                    Artifact(model.file, model.url, model.sha256, model.size),
                    model_path,
                    progress=self._report,
                    label=model.file,
                )
            state = {
                "runtime_tag": tag,
                "variant": variant,
                "server": str(server),
                "model": {
                    **model.__dict__,
                    "path": str(model_path),
                    "runtime_tag": tag,
                    "installed_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
                },
            }
            self._save(state)
            (model_path.with_suffix(model_path.suffix + ".json")).write_text(
                json.dumps(
                    {
                        "source": model.url,
                        "sha256": model.sha256,
                        "license": model.license,
                        "license_accepted_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
                    },
                    indent=2,
                ),
                encoding="utf-8",
            )
            self.progress["status"] = "starting_runtime"
            await asyncio.to_thread(self.start_runtime)
            on_ready()
            self.progress = {"status": "completed", "model": model.label, "error": None}
        except RuntimeError_ as exc:
            self.progress.update({"status": "failed", "error": exc.message})
        except Exception as exc:  # unerwartet → verständlich melden, Core läuft weiter
            log.exception("runtime setup failed")
            self.progress.update({"status": "failed", "error": f"{type(exc).__name__}: {exc}"})

    def start_runtime(self) -> bool:
        """Startet die verwaltete Runtime (falls eingerichtet) und schreibt ``models.toml``."""
        state = self.state()
        model = state.get("model")
        server = Path(state.get("server", ""))
        if not model or not server.is_file() or not Path(model["path"]).is_file():
            return False
        port = free_port(8080)
        self.process.start(server, model, port, gpu=state.get("variant") == "cuda12")
        self.process.wait_ready()
        if not self._custom_config():
            self.layout.models_config.write_text(models_toml(model, port), encoding="utf-8")
        return True

    def set_lora(self, adapters: list[str], active_name: str | None = None) -> None:
        """Aktiviert (oder mit leerer Liste: deaktiviert) einen freigegebenen NOVA-Adapter."""
        state = self.state()
        if not state.get("model"):
            raise RuntimeError_("not_installed", "No managed runtime installed")
        state["model"]["lora"] = adapters
        state["model"]["active_name"] = active_name if adapters else None
        self._save(state)

    def stop(self) -> None:
        self.process.stop()
